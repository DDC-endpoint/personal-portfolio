// The tiny ASCII portrait inside the "This Portfolio" card's skeleton — the
// V3 hero drawn at 28×21 cells with the hero's own maths (lib/portrait.js),
// so the recursive card matches the real portrait. Writes lib/miniPortrait.js.
//
// Usage: node scripts/mini-portrait.mjs

import sharp from "sharp";
import { writeFile } from "node:fs/promises";
import { buildField, density, glyphIndex, RAMP } from "../lib/portrait.js";

const COLS = 28, ROWS = 21, SS = 3; // 28×21 mono cells (~0.6 wide) keep the 4:5 stage
const { data } = await sharp("public/hero/portrait.webp")
  .ensureAlpha()
  .resize(COLS * SS, ROWS * SS, { fit: "fill" })
  .raw()
  .toBuffer({ resolveWithObject: true });

const field = buildField(data, COLS, ROWS, SS);
const rows = [];
for (let r = 0; r < ROWS; r++) {
  let row = "";
  for (let c = 0; c < COLS; c++) {
    const d = density(field, r * COLS + c, false);
    row += d > 0 ? RAMP[glyphIndex(d)] : " ";
  }
  rows.push(row);
}

const src = `// Generated by scripts/mini-portrait.mjs — don't edit by hand.
// The V3 hero portrait at ${COLS}×${ROWS} cells, for the "This Portfolio" card.
export const MINI_PORTRAIT = ${JSON.stringify(rows, null, 2)};
`;
await writeFile("lib/miniPortrait.js", src);
console.log(rows.join("\n"));
